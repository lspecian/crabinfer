//! Continuous batching engine loop.
//!
//! The engine loop runs in a dedicated thread, repeatedly:
//! 1. Draining new requests from the submission channel
//! 2. Running the scheduler to decide what to compute
//! 3. Building batched inputs and running the model forward pass
//! 4. Sampling output tokens and sending them to clients
//! 5. Checking stop conditions and cleaning up finished sequences
//!
//! The async HTTP handlers communicate with the engine loop through:
//! - `std::sync::mpsc` channel for submitting requests (non-blocking send)
//! - `tokio::sync::mpsc` per-request channels for receiving generated tokens

