/// A single token's log probability info.
#[derive(Debug, Clone)]
pub struct TokenLogprob {
    /// Token ID.
    pub token_id: u32,
    /// Log probability of this token.
    pub logprob: f32,
}

/// Token generated by the serving engine, sent to clients via channel.
#[derive(Debug, Clone)]
pub struct GeneratedToken {
    /// The generated token ID.
    pub token_id: u32,
    /// If set, generation is complete and this is the reason.
    pub finish_reason: Option<FinishReason>,
    /// Log probability of the sampled token (if logprobs requested).
    pub logprob: Option<f32>,
    /// Top log probabilities at this position (if top_logprobs requested).
    pub top_logprobs: Option<Vec<TokenLogprob>>,
}

/// Configuration for the serving engine.
#[derive(Debug, Clone)]
pub struct ServingEngineConfig {
    /// Maximum concurrent sequences.
    pub max_num_seqs: usize,
    /// Maximum tokens per scheduling step.
    pub max_num_batched_tokens: usize,
    /// Tokens per KV cache block. Must be a power of 2 between 8 and 64.
    /// Default: 16.
    pub block_size: usize,
    /// Number of KV cache blocks to allocate.
    ///
    /// If `None`, the engine will automatically calculate the optimal number
    /// based on available GPU memory, model weight size, and `gpu_memory_utilization`.
    pub num_kv_cache_blocks: Option<usize>,
    /// Enable prefix caching.
    pub enable_prefix_cache: bool,
    /// Fraction of GPU memory to use (0.0–1.0). Only used when
    /// `num_kv_cache_blocks` is `None` (auto mode). Default: 0.90.
    pub gpu_memory_utilization: f64,
    /// Low watermark: fraction of total KV cache blocks (0.0–1.0).
    /// When usage exceeds this, stop admitting new prefills. Default: 0.80.
    pub watermark_low: f64,
    /// High watermark: fraction of total KV cache blocks (0.0–1.0).
    /// When usage exceeds this, begin aggressive preemption. Default: 0.95.
    pub watermark_high: f64,
    /// Disable CUDA graphs and always use eager execution.
    /// Corresponds to vLLM's `--enforce-eager` flag. Default: false.
    pub enforce_eager: bool,
    /// Maximum batch size for CUDA graph capture. Graphs are pre-captured
    /// for batch sizes 1, 2, 4, ..., up to this value. Default: 32.
    pub max_cuda_graph_batch_size: usize,
    /// Weight quantization method applied at model load time. Default: None.
    pub quantization: super::quantization::QuantizationMethod,
    /// KV cache dtype. Lower precision saves memory at minimal accuracy cost.
    /// - `Auto`: use the serving dtype (resolved from `serving_dtype` field)
    /// - `F16`: half-precision — 2x more context vs F32
    /// - `BF16`: bfloat16 — 2x more context, better dynamic range than F16
    pub kv_cache_dtype: super::quantization::KVCacheDType,
    /// Model weight computation dtype. Default: `Auto` (detect best for device).
    /// - `Auto`: BF16 on Ampere+, F16 on Volta+, F32 elsewhere
    /// - `BF16`: requires Ampere (sm_80+) on CUDA; allowed on CPU
    /// - `F16`: half-precision, supported on Volta+ GPUs
    /// - `F32`: full precision, always available
    pub serving_dtype: super::quantization::ServingDType,
    /// Maximum model context length (max sequence length).
    /// When `None`, uses the model's built-in context length from GGUF metadata.
    /// When set, overrides the model's default (useful for models that support
    /// longer contexts via RoPE scaling).
    pub max_model_len: Option<usize>,
    /// Enable LoRA adapter serving.
    pub enable_lora: bool,
    /// Maximum number of LoRA adapters to keep in GPU memory simultaneously.
    /// Least-recently-used adapters are evicted when this limit is reached.
    pub max_loras: usize,
    /// Pre-registered LoRA adapter modules: `(name, path)` pairs.
    /// These are loaded lazily on first request for the adapter.
    pub lora_modules: Vec<(String, String)>,
    /// Number of GPUs for tensor parallelism. Default: 1 (no TP).
    /// When > 1, model weights are sharded across GPUs using NCCL.
    pub tensor_parallel_size: usize,
    /// Number of pipeline parallel stages. Default: 1 (disabled).
    /// When > 1, model layers are partitioned across stages for pipeline parallelism.
    pub pipeline_parallel_stages: usize,
}

